[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Build,
    [Parameter(Mandatory)][string]$OutputDirectory,
    [Parameter(Mandatory)][string]$LlvmBin,
    [string]$TitleConfig,
    [string]$LlvmLicense,
    [string]$BuildProvenance,
    [string]$MsvcLib,
    [string]$UcrtLib,
    [Parameter(Mandatory)][string]$VcRedist,
    [Parameter(Mandatory)][string]$DependencySources,
    [Parameter(Mandatory)][string]$DxcLicense,
    [Parameter(Mandatory)][string]$DxcThirdPartyNotices
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression
$root = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$buildPath = (Resolve-Path -LiteralPath $Build).Path
$referenceLink = [bool]$MsvcLib -and [bool]$UcrtLib
if (($MsvcLib -or $UcrtLib) -and !$referenceLink) {
    throw 'Supply both -MsvcLib and -UcrtLib to package the reference guest link.'
}
$entries = [Collections.Generic.SortedDictionary[string,string]]::new([StringComparer]::Ordinal)
function Add-File([string]$Name, [string]$Source) {
    $item = Get-Item -LiteralPath $Source
    if ($item -isnot [IO.FileInfo]) { throw "Expected a file at $Source" }
    $entries.Add($Name, $item.FullName)
}

Add-File Bulletproof.exe "$buildPath/Bulletproof_portable.exe"
Add-File dxcompiler.dll "$buildPath/dxcompiler.dll"
if (Test-Path -LiteralPath "$buildPath/dxil.dll" -PathType Leaf) {
    Add-File dxil.dll "$buildPath/dxil.dll"
}
foreach ($library in 'msvcp140.dll', 'vcruntime140.dll', 'vcruntime140_1.dll') {
    Add-File $library "$VcRedist/$library"
    Add-File "compiler/$library" "$VcRedist/$library"
}
Add-File compiler/xbe_recomp.exe "$buildPath/xbe_recomp.exe"
foreach ($tool in 'clang.exe', 'lld-link.exe') {
    Add-File "compiler/$tool" "$LlvmBin/$tool"
}
$support = "$buildPath/Bulletproof_portable_support"
if ($referenceLink) {
    foreach ($library in 'msvcrt.lib', 'vcruntime.lib') {
        Add-File "compiler/lib/$library" "$MsvcLib/$library"
    }
    Add-File compiler/lib/ucrt.lib "$UcrtLib/ucrt.lib"
    $linkProvenance = 'Reference package. The Microsoft SDK and Build Tools archives are internal validation inputs only.'
} else {
    foreach ($library in 'xbe-vcruntime.lib', 'xbe-ucrt-heap.lib', 'xbe-ucrt-math.lib') {
        Add-File "compiler/lib/$library" "$support/lib/$library"
    }
    Add-File compiler/portable_guest_crt.cc "$root/sdk/linux/runtime/app/portable_guest_crt.cc"
    $linkProvenance = 'The guest import archives were generated by LLD from project .def files in sdk/linux/cmake/windows_guest.'
}
if (!$TitleConfig) { $TitleConfig = "$root/config/game.toml" }
Add-File compiler/config/game.toml $TitleConfig
Add-File compiler/xdk/5849/layout.toml "$root/sdk/xdk/5849/layout.toml"
foreach ($header in 'cpu/x86_ops.h', 'cpu/x86_context.h', 'audio/apu_clock.h', 'app/portable_guest_abi.h') {
    Add-File "compiler/include/$header" "$root/sdk/linux/runtime/$header"
}
foreach ($header in 'cmath', 'cstdint', 'cstring', 'limits', 'type_traits') {
    Add-File "compiler/freestanding/$header" "$root/sdk/runtime/cpu/freestanding/$header"
}
Add-File compiler/portable_guest_module.cc "$root/sdk/linux/runtime/app/portable_guest_module.cc"
foreach ($file in 'guest.def', 'guest_hook_list.inc', 'guest_hook_defines.h') {
    Add-File "compiler/$file" "$support/$file"
}

Add-File LICENSES/Bulletproof-MIT.txt "$root/LICENSE"
Add-File LICENSES/THIRD_PARTY_NOTICES.md "$root/THIRD_PARTY_NOTICES.md"
Add-File LICENSES/SDK-THIRD-PARTY.txt "$root/sdk/THIRD_PARTY.txt"
if ($BuildProvenance) { Add-File LICENSES/BUILD-INPUTS.txt $BuildProvenance }
Add-File LICENSES/SDK.txt "$root/sdk/LICENSE"
if (!$LlvmLicense) { $LlvmLicense = "$root/sdk/tools/LLVM-LICENSE.txt" }
Add-File LICENSES/LLVM.txt $LlvmLicense
Add-File LICENSES/DXC.txt $DxcLicense
Add-File LICENSES/DXC-ThirdPartyNotices.txt $DxcThirdPartyNotices
Add-File LICENSES/SDL3.txt "$DependencySources/sdl3-src/LICENSE.txt"
Add-File LICENSES/ImGui.txt "$DependencySources/imgui-src/LICENSE.txt"
Add-File LICENSES/tomlplusplus.txt "$DependencySources/tomlplusplus-src/LICENSE"
Add-File LICENSES/Zydis.txt "$DependencySources/zydis-src/LICENSE"
Add-File LICENSES/Zycore.txt "$DependencySources/zydis-src/dependencies/zycore/LICENSE"
if (Test-Path "$DependencySources/vulkan-headers") {
    Add-File LICENSES/Vulkan-Headers.md "$DependencySources/vulkan-headers/LICENSE.md"
    Add-File LICENSES/Vulkan-Headers-Apache-2.0.txt "$DependencySources/vulkan-headers/LICENSES/Apache-2.0.txt"
    Add-File LICENSES/Vulkan-Headers-MIT.txt "$DependencySources/vulkan-headers/LICENSES/MIT.txt"
    Add-File LICENSES/Vulkan-Loader.txt "$DependencySources/vulkan-loader/LICENSE.txt"
}

$readme = @'
50 Cent: Bulletproof – PC Port
Native Vulkan PC Port for Windows and Linux
Windows x64 internal validation package

Extract the entire ZIP to a writable folder.
Place your original supported Xbox game ISO in assets/.
Open Bulletproof.exe. The first launch prepares the game locally and shows
progress. Esc or closing the preparation window cancels. Launch again to retry.
Later launches reuse the module. Keep userdata/ with the folder when moving it.

Requires Windows 11 x64 and a Vulkan-capable GPU with a working Vulkan driver.
No developer tools or Internet connection are needed at run time.
Runtime and preparation logs are in userdata/logs/.
The port's own contributions use MIT. See LICENSES/ for third-party notices
and provenance. Public redistribution clearance is pending.
'@
$provenance = @'
Internal validation only.

Bulletproof.exe and xbe_recomp.exe are built from this project's Vulkan SDK,
runtime and hooks. See SDK.txt and the third-party notices beside this file.
The project's own contributions use MIT. The game configuration and XDK
layout remain subject to their separate publication review.

clang.exe and lld-link.exe come from the Windows LLVM toolchain used to
produce the package. See LLVM.txt. dxcompiler.dll and dxil.dll, when present,
come from the DirectX Shader Compiler release. See DXC.txt.
The upstream notice inventory is in DXC-ThirdPartyNotices.txt.

msvcp140.dll, vcruntime140.dll and vcruntime140_1.dll come from the Visual
C++ x64 app-local redistributable set. Microsoft distribution terms apply.
The system provides Windows components and the Vulkan loader/GPU driver.

The freestanding headers and guest bridge sources come from the SDK.
The three guest bridge metadata files are generated from the host build.
File versions and hashes below identify the package inputs.
'@
$identity = foreach ($entry in $entries.GetEnumerator()) {
    if ($entry.Key -match '\.(exe|dll|lib)$') {
        $version = (Get-Item -LiteralPath $entry.Value).VersionInfo.FileVersion
        $hash = (Get-FileHash -LiteralPath $entry.Value -Algorithm SHA256).Hash
        "$hash  $($entry.Key)  $version".TrimEnd()
    }
}
$generated = @{
    'assets/' = ''
    'README.txt' = $readme + "`n"
    'LICENSES/PROVENANCE.txt' = $provenance + "`n`n$linkProvenance`n`n" + ($identity -join "`n") + "`n"
}
foreach ($name in $generated.Keys) { $entries.Add($name, '') }

$destination = (New-Item -ItemType Directory -Path $OutputDirectory -Force).FullName
$output = Join-Path $destination 'Bulletproof-windows-x86_64-internal.zip'
$temp = Join-Path $destination ([IO.Path]::GetRandomFileName())
$timestamp = [DateTimeOffset]::new(2000, 1, 1, 0, 0, 0, [TimeSpan]::Zero)
try {
    $stream = [IO.File]::Open($temp, [IO.FileMode]::CreateNew)
    try {
        $zip = [IO.Compression.ZipArchive]::new($stream, [IO.Compression.ZipArchiveMode]::Create, $true)
        try {
            foreach ($entry in $entries.GetEnumerator()) {
                $member = $zip.CreateEntry($entry.Key, [IO.Compression.CompressionLevel]::Optimal)
                $member.LastWriteTime = $timestamp
                if ($entry.Key.EndsWith('/')) { continue }
                $writer = $member.Open()
                try {
                    if ($generated.ContainsKey($entry.Key)) {
                        $value = $generated[$entry.Key].Replace("`r`n", "`n")
                        $bytes = [Text.Encoding]::UTF8.GetBytes($value)
                        $writer.Write($bytes, 0, $bytes.Length)
                    } else {
                        $reader = [IO.File]::OpenRead($entry.Value)
                        try { $reader.CopyTo($writer) } finally { $reader.Dispose() }
                    }
                } finally { $writer.Dispose() }
            }
        } finally { $zip.Dispose() }
    } finally { $stream.Dispose() }
    if ([IO.File]::Exists($output)) { [IO.File]::Replace($temp, $output, [NullString]::Value) }
    else { [IO.File]::Move($temp, $output) }
    Get-Item -LiteralPath $output
} finally {
    if ([IO.File]::Exists($temp)) { [IO.File]::Delete($temp) }
}
